const fs = require("fs");
const path = require("path");

if (process.env.DATABASE_URL) {
    const { Pool } = require("pg");
    const pool = new Pool({
        connectionString: process.env.DATABASE_URL,
        ssl: { rejectUnauthorized: false }
    });

    pool.on("connect", () => {
        console.log("✅ Connecté à PostgreSQL.");
    });

    pool.on("error", (err) => {
        console.error("❌ Erreur PostgreSQL :", err.message);
    });
    pool.databaseProvider = new URL(process.env.DATABASE_URL).hostname.endsWith(".neon.tech")
        ? "Neon PostgreSQL"
        : "PostgreSQL";

    pool.ready = Promise.all([
        pool.query(`
            CREATE TABLE IF NOT EXISTS users (
                id SERIAL PRIMARY KEY,
                username TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL
            )
        `),
        pool.query(`
            CREATE TABLE IF NOT EXISTS orders (
                id SERIAL PRIMARY KEY,
                client TEXT NOT NULL,
                reference TEXT NOT NULL UNIQUE,
                total REAL NOT NULL,
                items TEXT NOT NULL,
                payment_method TEXT,
                transaction_reference TEXT,
                payment_status TEXT NOT NULL DEFAULT 'pending',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `)
    ]).then(async () => {
        await pool.query("ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_method TEXT");
        await pool.query("ALTER TABLE orders ADD COLUMN IF NOT EXISTS transaction_reference TEXT");
        await pool.query("ALTER TABLE orders ADD COLUMN IF NOT EXISTS payment_status TEXT NOT NULL DEFAULT 'pending'");
        await pool.query(`
            CREATE UNIQUE INDEX IF NOT EXISTS orders_transaction_reference_unique
            ON orders (transaction_reference)
            WHERE transaction_reference IS NOT NULL AND transaction_reference <> ''
        `);
        await pool.query(`
            CREATE TABLE IF NOT EXISTS payment_alerts (
                id SERIAL PRIMARY KEY,
                order_id INTEGER,
                transaction_reference TEXT NOT NULL UNIQUE,
                expected_reference TEXT,
                amount REAL NOT NULL,
                expected_amount REAL,
                sender_phone TEXT,
                message TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                resolved_at TIMESTAMP
            )
        `);
        await pool.query(`
            CREATE TABLE IF NOT EXISTS device_pairing_codes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                phone_number VARCHAR(20) NOT NULL,
                code_hash CHAR(64) NOT NULL,
                expires_at TIMESTAMPTZ NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        `);
        await pool.query(`
            CREATE INDEX IF NOT EXISTS idx_pairing_code_hash
            ON device_pairing_codes (code_hash)
        `);
        await pool.query(`
            CREATE INDEX IF NOT EXISTS idx_pairing_expiration
            ON device_pairing_codes (expires_at)
        `);
        await pool.query(`
            CREATE TABLE IF NOT EXISTS device_tokens (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                phone_number VARCHAR(20) NOT NULL,
                token_hash CHAR(64) NOT NULL UNIQUE,
                expires_at TIMESTAMPTZ NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        `);
        await pool.query(`
            CREATE INDEX IF NOT EXISTS idx_device_token_expiration
            ON device_tokens (expires_at)
        `);
        await pool.query(`
            CREATE TABLE IF NOT EXISTS transactions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                reference TEXT NOT NULL UNIQUE,
                montant NUMERIC(18, 2) NOT NULL,
                expediteur TEXT,
                destinataire TEXT,
                nom_expediteur VARCHAR(100),
                nom_destinataire VARCHAR(100),
                numero_emetteur_sms VARCHAR(30),
                type_transaction VARCHAR(20) NOT NULL,
                date_transaction TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                source VARCHAR(40) NOT NULL DEFAULT 'manual',
                owner_phone VARCHAR(20),
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                legacy_data JSONB NOT NULL DEFAULT '{}'::jsonb
            )
        `);
        await pool.query(`
            ALTER TABLE transactions
            ADD COLUMN IF NOT EXISTS owner_phone VARCHAR(20),
            ADD COLUMN IF NOT EXISTS nom_expediteur VARCHAR(100),
            ADD COLUMN IF NOT EXISTS nom_destinataire VARCHAR(100),
            ADD COLUMN IF NOT EXISTS numero_emetteur_sms VARCHAR(30),
            ADD COLUMN IF NOT EXISTS source VARCHAR(40) NOT NULL DEFAULT 'manual',
            ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            ADD COLUMN IF NOT EXISTS legacy_data JSONB NOT NULL DEFAULT '{}'::jsonb
        `);
        await pool.query(`
            CREATE INDEX IF NOT EXISTS idx_transactions_owner_date
            ON transactions (owner_phone, date_transaction DESC)
        `);
        await pool.query(`
            CREATE TABLE IF NOT EXISTS device_notifications (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                owner_phone VARCHAR(20) NOT NULL,
                event_type VARCHAR(40) NOT NULL,
                event_at TIMESTAMPTZ NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        `);
        await pool.query(`
            CREATE INDEX IF NOT EXISTS idx_device_notification_owner_date
            ON device_notifications (owner_phone, event_at)
        `);
    }).then(() => {
        console.log("✅ Tables PostgreSQL prêtes.");
    });

    pool.isPostgres = true;
    module.exports = pool;
} else {
    if (process.env.NODE_ENV === "production" || process.env.RENDER === "true") {
        throw new Error("DATABASE_URL est requise en production pour utiliser PostgreSQL.");
    }

    const initSqlJs = require("sql.js");
    const databasePath = process.env.SHOPIX_SQLITE_PATH || path.join(__dirname, "users.db");
    let sqliteDatabase;
    let sqliteTransactionActive = false;

    const databaseReady = initSqlJs().then((SQL) => {
        const existingData = fs.existsSync(databasePath)
            ? new Uint8Array(fs.readFileSync(databasePath))
            : undefined;
        sqliteDatabase = new SQL.Database(existingData);
        sqliteDatabase.run(`
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                username TEXT NOT NULL,
                email TEXT UNIQUE NOT NULL,
                password TEXT NOT NULL
            )
        `);
        sqliteDatabase.run(`
            CREATE TABLE IF NOT EXISTS orders (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                client TEXT NOT NULL,
                reference TEXT NOT NULL UNIQUE,
                total REAL NOT NULL,
                items TEXT NOT NULL,
                payment_method TEXT,
                transaction_reference TEXT,
                payment_status TEXT NOT NULL DEFAULT 'pending',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        `);
        const orderColumns = sqliteDatabase
            .exec("PRAGMA table_info(orders)")[0]
            ?.values.map((column) => column[1]) || [];
        if (!orderColumns.includes("payment_method")) {
            sqliteDatabase.run("ALTER TABLE orders ADD COLUMN payment_method TEXT");
        }
        if (!orderColumns.includes("transaction_reference")) {
            sqliteDatabase.run("ALTER TABLE orders ADD COLUMN transaction_reference TEXT");
        }
        if (!orderColumns.includes("payment_status")) {
            sqliteDatabase.run(
                "ALTER TABLE orders ADD COLUMN payment_status TEXT NOT NULL DEFAULT 'pending'"
            );
        }
        sqliteDatabase.run(`
            CREATE UNIQUE INDEX IF NOT EXISTS orders_transaction_reference_unique
            ON orders (transaction_reference)
            WHERE transaction_reference IS NOT NULL AND transaction_reference <> ''
        `);
        sqliteDatabase.run(`
            CREATE TABLE IF NOT EXISTS payment_alerts (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                order_id INTEGER,
                transaction_reference TEXT NOT NULL UNIQUE,
                expected_reference TEXT,
                amount REAL NOT NULL,
                expected_amount REAL,
                sender_phone TEXT,
                message TEXT NOT NULL,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                resolved_at TIMESTAMP
            )
        `);
        sqliteDatabase.run(`
            CREATE TABLE IF NOT EXISTS device_pairing_codes (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                phone_number TEXT NOT NULL,
                code_hash TEXT NOT NULL,
                expires_at TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        `);
        sqliteDatabase.run(`
            CREATE TABLE IF NOT EXISTS device_tokens (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                phone_number TEXT NOT NULL,
                token_hash TEXT NOT NULL UNIQUE,
                expires_at TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        `);
        sqliteDatabase.run(`
            CREATE TABLE IF NOT EXISTS transactions (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                reference TEXT NOT NULL UNIQUE,
                montant NUMERIC NOT NULL,
                expediteur TEXT,
                destinataire TEXT,
                nom_expediteur TEXT,
                nom_destinataire TEXT,
                numero_emetteur_sms TEXT,
                type_transaction TEXT NOT NULL,
                date_transaction TEXT DEFAULT CURRENT_TIMESTAMP,
                source TEXT NOT NULL DEFAULT 'manual',
                owner_phone TEXT,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
                legacy_data TEXT NOT NULL DEFAULT '{}'
            )
        `);
        sqliteDatabase.run(`
            CREATE TABLE IF NOT EXISTS device_notifications (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                owner_phone TEXT NOT NULL,
                event_type TEXT NOT NULL,
                event_at TEXT NOT NULL,
                created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        `);
        sqliteDatabase.run(`
            CREATE INDEX IF NOT EXISTS idx_transactions_owner_date
            ON transactions (owner_phone, date_transaction DESC)
        `);
        sqliteDatabase.run(`
            CREATE INDEX IF NOT EXISTS idx_device_notification_owner_date
            ON device_notifications (owner_phone, event_at)
        `);
        fs.writeFileSync(databasePath, Buffer.from(sqliteDatabase.export()));
        console.log("✅ Base SQLite locale prête.");
    });

    module.exports = {
        isPostgres: false,
        ready: databaseReady,
        async connect() {
            await databaseReady;
            return {
                query: (sql, params = []) => module.exports.query(sql, params),
                release() {}
            };
        },
        async query(sql, params = []) {
            await databaseReady;
            if (/^\s*(BEGIN|COMMIT|ROLLBACK)\s*;?\s*$/i.test(sql)) {
                sqliteDatabase.run(sql);
                if (/^\s*BEGIN/i.test(sql)) {
                    sqliteTransactionActive = true;
                } else if (/^\s*COMMIT/i.test(sql)) {
                    sqliteTransactionActive = false;
                    fs.writeFileSync(databasePath, Buffer.from(sqliteDatabase.export()));
                } else {
                    sqliteTransactionActive = false;
                }
                return { rows: [], rowCount: 0 };
            }
            const statement = sqliteDatabase.prepare(sql);
            try {
                statement.bind(params);
                const rows = [];
                while (statement.step()) {
                    rows.push(statement.getAsObject());
                }
                const isReadQuery = /^\s*(SELECT|PRAGMA|WITH)\b/i.test(sql);
                if (!isReadQuery && !sqliteTransactionActive) {
                    fs.writeFileSync(databasePath, Buffer.from(sqliteDatabase.export()));
                }
                return {
                    rows,
                    rowCount: isReadQuery ? rows.length : sqliteDatabase.getRowsModified()
                };
            } finally {
                statement.free();
            }
        }
    };
}